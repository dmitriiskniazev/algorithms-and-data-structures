from typing import Protocol


class Deque[T](Protocol):
    def __len__(self) -> int: ...
    def push_front(self, value: T) -> None: ...
    def push_back(self, value: T) -> None: ...
    def pop_front(self) -> T: ...
    def pop_back(self) -> T: ...
    def front(self) -> T: ...
    def back(self) -> T: ...
